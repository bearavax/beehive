function normName(value: string) {
  return value
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

export function memberBySlug(slug: string) {
  return members.find((member) => member.slug === slug);
}

/** Match a Mātai Manapori display name. A vote-list name is not treated as proof of a committee seat. */
export function matchMember(voteName: string): Member | undefined {
  const name = normName(voteName);
  return members.find(
    (member) =>
      member.voteAliases.some((alias) => normName(alias) === name) || name.endsWith(normName(member.name)),
  );
}

